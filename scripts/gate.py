#!/usr/bin/env python3
"""Acceptance gate runner (spec section 15.1).

Usage:
    uv run python scripts/gate.py --stage 3      # stages 0..3 + regression
    uv run python scripts/gate.py --all          # stages 0..9 + regression
    uv run python scripts/gate.py --render       # re-render docs/acceptance-matrix.md only

The gate fails (nonzero exit) when:
  * pytest fails, or
  * any acceptance ID of an included stage has no passing tagged test and no explicit
    BLOCKED/UNVALIDATED status in docs/acceptance/requirements.toml, or
  * a tagged test references an unknown acceptance ID.

CI calls exactly this script.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import platform
import subprocess
import sys
import time
import tomllib
import xml.etree.ElementTree as ET  # noqa: S405 - parsing our own pytest output
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REQS = ROOT / "docs" / "acceptance" / "requirements.toml"
REPORTS = ROOT / "artifacts" / "test-reports"
MATRIX_MD = ROOT / "docs" / "acceptance-matrix.md"
MAX_STAGE = 9


def load_requirements() -> list[dict]:
    with REQS.open("rb") as fh:
        data = tomllib.load(fh)
    reqs = data.get("req", [])
    ids = [r["id"] for r in reqs]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        raise SystemExit(f"duplicate acceptance IDs: {sorted(dupes)}")
    return reqs


def git_info() -> dict:
    def run(*args: str) -> str:
        try:
            return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=False).stdout.strip()
        except OSError:
            return ""

    commit = run("rev-parse", "HEAD")
    dirty = run("status", "--porcelain")
    return {"commit": commit or None, "dirty": bool(dirty)}


def parse_junit(path: Path) -> dict[str, list[tuple[str, str]]]:
    """Map acceptance ID -> list of (test nodeid, outcome)."""
    results: dict[str, list[tuple[str, str]]] = defaultdict(list)
    if not path.exists():
        return results
    tree = ET.parse(path)  # noqa: S314 - trusted local file
    for case in tree.iter("testcase"):
        name = f"{case.get('classname')}::{case.get('name')}"
        outcome = "passed"
        for child in case:
            if child.tag in ("failure", "error"):
                outcome = "failed"
            elif child.tag == "skipped":
                outcome = "skipped"
        props = case.find("properties")
        if props is None:
            continue
        for prop in props.iter("property"):
            if prop.get("name") == "acceptance":
                results[prop.get("value", "")].append((name, outcome))
    return results


def latest_results() -> dict[str, list[tuple[str, str]]]:
    merged: dict[str, list[tuple[str, str]]] = defaultdict(list)
    summary = REPORTS / "latest-acceptance.json"
    if summary.exists():
        data = json.loads(summary.read_text())
        for acc_id, entries in data.get("results", {}).items():
            merged[acc_id] = [tuple(e) for e in entries]
    return merged


def evaluate(reqs: list[dict], results: dict, max_stage: int) -> tuple[list[dict], list[str]]:
    rows, problems = [], []
    known = {r["id"] for r in reqs}
    for acc_id in results:
        if acc_id not in known:
            problems.append(f"test references unknown acceptance ID {acc_id}")
    for r in reqs:
        if r["stage"] > max_stage:
            continue
        tests = results.get(r["id"], [])
        override = r.get("status")
        passed = [t for t in tests if t[1] == "passed"]
        failed = [t for t in tests if t[1] != "passed"]
        if override in ("BLOCKED", "UNVALIDATED"):
            state = override
            if failed and override == "UNVALIDATED":
                state = "UNVALIDATED"
        elif failed:
            state = "FAIL"
            problems.append(f"{r['id']}: failing tests: {[t[0] for t in failed]}")
        elif passed:
            state = "PASS"
        else:
            state = "MISSING"
            problems.append(f"{r['id']}: no tagged test and no BLOCKED/UNVALIDATED status")
        rows.append({**r, "state": state, "tests": tests})
    return rows, problems


def render_matrix(reqs: list[dict], results: dict) -> None:
    rows, _ = evaluate(reqs, results, MAX_STAGE)
    lines = [
        "# Acceptance matrix",
        "",
        "Generated by `scripts/gate.py` from `docs/acceptance/requirements.toml` and the most recent",
        "JUnit results in `artifacts/test-reports/`. Do not edit by hand.",
        "",
        f"Rendered: {dt.datetime.now(dt.UTC).strftime('%Y-%m-%dT%H:%M:%SZ')}",
        "",
        "States: PASS (all tagged tests passed in the latest gate run), FAIL, MISSING (no test yet),",
        "BLOCKED (external dependency missing), UNVALIDATED (mechanics may work; scientific target not met",
        "or not yet evaluated).",
        "",
    ]
    by_stage: dict[int, list[dict]] = defaultdict(list)
    for row in rows:
        by_stage[row["stage"]].append(row)
    for stage in sorted(by_stage):
        lines += [f"## Stage {stage}", "", "| ID | State | Spec | Requirement | Tests |", "| --- | --- | --- | --- | --- |"]
        for row in by_stage[stage]:
            tests = len(row["tests"])
            note = row["text"]
            if row.get("reason"):
                note += f" **{row.get('status')}:** {row['reason']} Needs: {row.get('needs', '')}"
            lines.append(f"| {row['id']} | {row['state']} | {row['section']} | {note} | {tests} |")
        lines.append("")
    MATRIX_MD.write_text("\n".join(lines))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", type=int)
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--render", action="store_true")
    ap.add_argument("--pytest-args", default="", help="extra args passed to pytest")
    args = ap.parse_args()

    reqs = load_requirements()
    stages_with_ids = {r["stage"] for r in reqs}
    missing_stages = set(range(MAX_STAGE + 1)) - stages_with_ids
    if missing_stages:
        print(f"stages without acceptance IDs: {sorted(missing_stages)}")
        return 2

    if args.render and args.stage is None and not args.all:
        render_matrix(reqs, latest_results())
        print(f"rendered {MATRIX_MD.relative_to(ROOT)}")
        return 0

    stage = MAX_STAGE if args.all else args.stage
    if stage is None or not 0 <= stage <= MAX_STAGE:
        ap.error("--stage N (0-9) or --all is required")

    REPORTS.mkdir(parents=True, exist_ok=True)
    paths = [f"tests/stage_{s:02d}" for s in range(stage + 1) if (ROOT / f"tests/stage_{s:02d}").exists()]
    paths.append("tests/regression")
    junit = REPORTS / f"stage_{stage:02d}.xml"
    cmd = [sys.executable, "-m", "pytest", *paths, f"--junitxml={junit}", "-o", "junit_family=xunit1", "-q"]
    if args.pytest_args:
        cmd += args.pytest_args.split()
    env = {**os.environ}
    t0 = time.monotonic()
    proc = subprocess.run(cmd, cwd=ROOT, env=env, check=False)
    elapsed = time.monotonic() - t0

    results = parse_junit(junit)
    rows, problems = evaluate(reqs, results, stage)
    counts: dict[str, int] = defaultdict(int)
    for row in rows:
        counts[row["state"]] += 1

    record = {
        "timestamp_utc": dt.datetime.now(dt.UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "stage": stage,
        "command": " ".join(cmd),
        "pytest_exit_status": proc.returncode,
        "elapsed_s": round(elapsed, 2),
        "python": sys.version.split()[0],
        "platform": platform.platform(),
        "machine": platform.machine(),
        "cpu_count": os.cpu_count(),
        "git": git_info(),
        "junit": str(junit.relative_to(ROOT)),
        "state_counts": dict(counts),
        "problems": problems,
    }
    with (REPORTS / "gate-log.jsonl").open("a") as fh:
        fh.write(json.dumps(record) + "\n")

    merged = latest_results()
    for acc_id, tests in results.items():
        merged[acc_id] = tests
    (REPORTS / "latest-acceptance.json").write_text(
        json.dumps({"updated_utc": record["timestamp_utc"], "results": merged}, indent=1, sort_keys=True)
    )
    render_matrix(reqs, merged)

    print("\n=== gate summary ===")
    print(json.dumps({k: record[k] for k in ("stage", "pytest_exit_status", "elapsed_s", "state_counts")}, indent=1))
    for row in rows:
        if row["state"] in ("BLOCKED", "UNVALIDATED"):
            print(f"  {row['state']:<11} {row['id']}: {row.get('reason', '')}")
    for p in problems:
        print(f"  PROBLEM {p}")
    ok = proc.returncode == 0 and not problems
    print("GATE PASSED" if ok else "GATE FAILED")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
